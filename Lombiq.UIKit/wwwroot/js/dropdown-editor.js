/**
 * Remove selected item from the dropdown list.
 * @param container {Element} The container around the button and dropdown list.
 * @param button {Element} The button next to the dropdown list.
 */
function removeSelectedFromDropDown(container, button) {
    const buttonText = button?.textContent.trim();
    const buttonItems = container.querySelectorAll('.dropdownEditor__itemParent');

    buttonItems.forEach(item => item.classList.toggle('d-none', buttonText === item.innerText.trim()));
}

/**
 * Adds click event handler to each dropdown item.
 * @param container {Element} The container around the button and dropdown list.
 * @param button {Element} The button next to the dropdown list.
 * @param aspId {string} The ID of the hidden input generated by ASP.NET Core.
 * @param removeSelected {boolean} Indicates whether `removeSelectedFromDropDown` should be called.
 */
function dropdownOnClick(container, button, aspId, removeSelected) {
    if (removeSelected) {
        removeSelectedFromDropDown(container, button);
    }

    container.querySelectorAll(`.dropdownEditor__item`)
        .forEach((item) => item.addEventListener('click', () => {
            const state = item.getAttribute('data-state');
            const text = item.getAttribute('data-state-text');

            const previousClass = button.getAttribute('data-selected-class');
            const newClass = item.getAttribute('data-class');

            button.textContent = text;
            button.classList.remove(previousClass);
            button.classList.add(newClass);
            button.setAttribute('data-selected-class', newClass);

            // Set hidden input value.
            document.getElementById(aspId).value = state;

            if (removeSelected) {
                removeSelectedFromDropDown(container, button);
            }
        }));
}

document.querySelectorAll('.dropdownEditor').forEach((item) =>
    dropdownOnClick(
        item,
        item.querySelector('.dropdownEditor__button'),
        item.getAttribute('data-asp-id'),
        item.getAttribute('data-hide-selected') === 'true'));
